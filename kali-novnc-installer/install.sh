#!/bin/sh
# Kali multi-user noVNC lab installer for Alpine Linux (run as root).
# Legitimate remote-desktop lab use only. See README.md.
write_files() { d=$1; mkdir -p "$d"
cat > "$d/Containerfile" <<'__EOF_Containerfile__'
# Kali remote-desktop lab image: XFCE + TigerVNC + noVNC, multi-user in one container.
FROM docker.io/kalilinux/kali-rolling:latest
ARG KALI_META="kali-linux-core"
ENV DEBIAN_FRONTEND=noninteractive LANG=C.UTF-8
RUN apt-get update && apt-get install -y --no-install-recommends \
      ${KALI_META} xfce4 xfce4-terminal dbus-x11 x11-xserver-utils \
      tigervnc-standalone-server tigervnc-tools novnc websockify \
      sudo procps passwd ca-certificates fonts-dejavu-core firefox-esr \
 && apt-get clean && rm -rf /var/lib/apt/lists/*
COPY entrypoint.sh /usr/local/bin/entrypoint.sh
RUN chmod 755 /usr/local/bin/entrypoint.sh
VOLUME ["/home"]
ENTRYPOINT ["/usr/local/bin/entrypoint.sh"]
__EOF_Containerfile__
cat > "$d/entrypoint.sh" <<'__EOF_entrypoint__'
#!/bin/bash
# Starts one Xvnc (:N) + one websockify/noVNC (127.0.0.1:BASE_PORT+N) per user.
# Input: /etc/kali-novnc/users.env lines "name:password" (mounted read-only).
set -u
CREDS=${CREDS_FILE:-/run/creds/users.env}
BASE_PORT=${BASE_PORT:-6080}
GEOMETRY=${GEOMETRY:-1600x900}
pids=()
trap 'kill "${pids[@]}" 2>/dev/null; exit 0' TERM INT

supervise() {  # supervise <name> <cmd...> : restart forever
  local n=$1; shift
  ( while true; do "$@"; echo "[$n] exited ($?), restarting in 2s" >&2; sleep 2; done ) &
  pids+=($!)
}

i=0
while IFS=: read -r user pass; do
  [ -z "$user" ] && continue; case $user in \#*) continue;; esac
  i=$((i+1)); disp=$i; port=$((BASE_PORT+i))
  id "$user" >/dev/null 2>&1 || useradd -m -s /bin/bash "$user"
  [ -d "/home/$user" ] || { mkdir -p "/home/$user"; cp -rT /etc/skel "/home/$user"; }
  echo "$user:$pass" | chpasswd
  install -d -o "$user" -g "$user" -m 700 "/home/$user/.vnc"
  printf '%s\n' "$pass" | vncpasswd -f > "/home/$user/.vnc/passwd"
  chown "$user:$user" "/home/$user/.vnc/passwd"; chmod 600 "/home/$user/.vnc/passwd"
  cat > "/home/$user/.vnc/xstartup" <<X
#!/bin/sh
unset SESSION_MANAGER DBUS_SESSION_BUS_ADDRESS
exec dbus-launch --exit-with-session startxfce4
X
  chown "$user:$user" "/home/$user/.vnc/xstartup"; chmod 755 "/home/$user/.vnc/xstartup"
  rm -f "/tmp/.X$disp-lock" "/tmp/.X11-unix/X$disp"
  supervise "vnc-$user" su - "$user" -c \
    "Xvnc :$disp -geometry $GEOMETRY -depth 24 -localhost -rfbport $((5900+disp)) \
       -SecurityTypes VncAuth -PasswordFile \$HOME/.vnc/passwd -AlwaysShared & XP=\$!; \
     sleep 2; DISPLAY=:$disp \$HOME/.vnc/xstartup; kill \$XP; wait \$XP"
  supervise "novnc-$user" websockify --web /usr/share/novnc "127.0.0.1:$port" "127.0.0.1:$((5900+disp))"
  echo "user=$user display=:$disp novnc=127.0.0.1:$port"
done < "$CREDS"
[ "$i" -eq 0 ] && { echo "no users in $CREDS" >&2; exit 1; }
wait
__EOF_entrypoint__
cat > "$d/nginx.conf.tmpl" <<'__EOF_nginx__'
# Generated by install.sh. __LOCATIONS__ is replaced per user.
server {
    listen 80;
    return 301 https://$host:__PUBLIC_PORT__$request_uri;
}
server {
    listen __PUBLIC_PORT__ ssl;
    http2 on;
    server_name __SERVER_NAME__;
    ssl_certificate     __CERT__;
    ssl_certificate_key __KEY__;
    ssl_protocols TLSv1.2 TLSv1.3;
    add_header X-Frame-Options SAMEORIGIN;
    add_header X-Content-Type-Options nosniff;
    location = / { default_type text/plain; return 200 "Kali noVNC lab. Go to /<username>/\n"; }
__LOCATIONS__
}
__EOF_nginx__
cat > "$d/kali-novnc.initd" <<'__EOF_kali-novnc__'
#!/sbin/openrc-run
name="kali-novnc"
description="Kali multi-user noVNC container (podman)"
: ${CONTAINER_NAME:=kali-novnc}
depend() { need net cgroups; after firewall; before nginx; }
start() {
  ebegin "Starting $CONTAINER_NAME"
  podman start "$CONTAINER_NAME" >/dev/null; eend $?
}
stop() {
  ebegin "Stopping $CONTAINER_NAME"
  podman stop -t 15 "$CONTAINER_NAME" >/dev/null; eend $?
}
status() {
  [ "$(podman inspect -f '{{.State.Running}}' "$CONTAINER_NAME" 2>/dev/null)" = true ] \
    && { einfo "running"; return 0; } || { einfo "stopped"; return 3; }
}
__EOF_kali-novnc__
}
# ---- main installer logic (embedded files are written above) ----
set -eu
[ "$(id -u)" = 0 ] || { echo "run as root" >&2; exit 1; }
[ -f /etc/alpine-release ] || echo "WARNING: not Alpine; continuing anyway" >&2

USERS=${USERS:-user1,user2,user3}
PUBLIC_PORT=${PUBLIC_PORT:-443}
CONTAINER_NAME=${CONTAINER_NAME:-kali-novnc}
IMAGE=${IMAGE:-localhost/kali-novnc:latest}
KALI_META=${KALI_META:-kali-linux-core}   # e.g. kali-linux-default (large)
BASE_PORT=${BASE_PORT:-6080}
DOMAIN=${DOMAIN:-}
EMAIL=${EMAIL:-}
REBUILD=${REBUILD:-0}
ETC=/etc/kali-novnc; SRC=$ETC/build; CREDS=$ETC/users.env
DATA=/var/lib/kali-novnc/home

echo "==> packages"
grep -Eq '^[^#].*/community' /etc/apk/repositories || \
  sed -i 's|^#\(.*/community\)$|\1|' /etc/apk/repositories
apk update >/dev/null
apk add --no-cache podman nginx openssl iptables ip6tables fuse-overlayfs >/dev/null
[ -n "$DOMAIN" ] && apk add --no-cache certbot certbot-nginx >/dev/null || true
rc-update add cgroups boot >/dev/null 2>&1 || true; rc-service cgroups start >/dev/null 2>&1 || true

umask 077; mkdir -p "$ETC" "$SRC" "$DATA"; touch "$CREDS"
gen() { openssl rand -base64 18 | tr -dc 'A-Za-z0-9' | cut -c1-16; }

echo "==> users / passwords"
NEW=""; TMP=$(mktemp)
IFS_OLD=$IFS; IFS=,
set -- $USERS; IFS=$IFS_OLD
idx=0
for u in "$@"; do
  idx=$((idx+1)); u=$(echo "$u" | tr -d ' ')
  echo "$u" | grep -Eq '^[a-z_][a-z0-9_-]{0,30}$' || { echo "bad username: $u" >&2; exit 1; }
  p=""
  if [ -n "${PASSWORDS:-}" ]; then p=$(echo "$PASSWORDS" | cut -d, -f$idx); fi
  [ -z "$p" ] && [ -n "${PASSWORD:-}" ] && p=$PASSWORD
  [ -z "$p" ] && p=$(grep "^$u:" "$CREDS" | cut -d: -f2- || true)
  [ -z "$p" ] && { p=$(gen); NEW="$NEW$u:$p\n"; }
  echo "$p" | grep -q ':' && { echo "password for $u must not contain ':'" >&2; exit 1; }
  echo "$u:$p" >> "$TMP"
done
mv "$TMP" "$CREDS"; chmod 600 "$CREDS"

echo "==> build context"
write_files "$SRC"
CHANGED=0
NEWSUM=$(cat "$SRC/Containerfile" "$SRC/entrypoint.sh" | sha256sum | cut -d' ' -f1)
[ "$(cat $ETC/.buildsum 2>/dev/null)" = "$NEWSUM:$KALI_META" ] || CHANGED=1
if [ "$REBUILD" = 1 ] || [ "$CHANGED" = 1 ] || ! podman image exists "$IMAGE"; then
  echo "==> building image (this takes a while)"
  podman build --build-arg KALI_META="$KALI_META" -t "$IMAGE" "$SRC"
  echo "$NEWSUM:$KALI_META" > $ETC/.buildsum
fi

echo "==> container"
podman rm -f "$CONTAINER_NAME" >/dev/null 2>&1 || true
podman run -d --name "$CONTAINER_NAME" --network host --shm-size 1g \
  --restart no -e BASE_PORT="$BASE_PORT" \
  -v "$DATA":/home:Z -v "$CREDS":/run/creds/users.env:ro,Z \
  "$IMAGE" >/dev/null
install -m 755 "$SRC/kali-novnc.initd" /etc/init.d/kali-novnc
echo "CONTAINER_NAME=$CONTAINER_NAME" > /etc/conf.d/kali-novnc
rc-update add kali-novnc default >/dev/null

echo "==> TLS + nginx"
CERT=$ETC/tls.crt; KEY=$ETC/tls.key
IP=$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src") print $(i+1)}')
NAME=${DOMAIN:-${IP:-_}}
if [ ! -s "$CERT" ]; then
  openssl req -x509 -newkey rsa:2048 -nodes -days 825 -keyout "$KEY" -out "$CERT" \
    -subj "/CN=$NAME" -addext "subjectAltName=${DOMAIN:+DNS:$DOMAIN,}IP:${IP:-127.0.0.1}" 2>/dev/null
fi
HT=/etc/nginx/kali-novnc.htpasswd.d; mkdir -p "$HT"; rm -f "$HT"/*
LOC=$(mktemp); i=0
while IFS=: read -r u p; do
  i=$((i+1)); port=$((BASE_PORT+i))
  printf '%s:%s\n' "$u" "$(openssl passwd -apr1 "$p")" > "$HT/$u"
  cat >> "$LOC" <<L
    location = /$u { return 301 /$u/; }
    location = /$u/ { auth_basic "$u"; auth_basic_user_file $HT/$u;
        return 302 /$u/vnc.html?path=$u/websockify&autoconnect=1&resize=remote; }
    location /$u/ {
        auth_basic "$u"; auth_basic_user_file $HT/$u;
        proxy_pass http://127.0.0.1:$port/;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header Host \$host;
        proxy_read_timeout 1d; proxy_send_timeout 1d; proxy_buffering off;
    }
L
done < "$CREDS"
chown -R root:nginx "$HT"; chmod 750 "$HT"; chmod 640 "$HT"/*
sed -e "s|__PUBLIC_PORT__|$PUBLIC_PORT|g" -e "s|__SERVER_NAME__|$NAME|" \
    -e "s|__CERT__|$CERT|" -e "s|__KEY__|$KEY|" "$SRC/nginx.conf.tmpl" \
  | awk -v f="$LOC" '/__LOCATIONS__/{while((getline l<f)>0)print l;next}1' \
  > /etc/nginx/http.d/kali-novnc.conf
rm -f "$LOC" /etc/nginx/http.d/default.conf
nginx -t
rc-update add nginx default >/dev/null
rc-service nginx restart >/dev/null 2>&1 || rc-service nginx start
if [ -n "$DOMAIN" ] && [ -n "$EMAIL" ]; then
  certbot --nginx -n --agree-tos -m "$EMAIL" -d "$DOMAIN" || echo "certbot failed; keeping self-signed"
fi

echo
echo "================ DONE ================"
while IFS=: read -r u p; do echo "  https://$NAME:$PUBLIC_PORT/$u/   (login: $u)"; done < "$CREDS"
[ -n "$NEW" ] && { echo; echo "Generated passwords (shown ONCE; also in $CREDS):"; printf "$NEW" | sed 's/^/  /'; } || true
echo "Basic-auth + VNC password are the same (VNC uses only the first 8 chars)."
echo "Firewall: allow only 22,80,$PUBLIC_PORT inbound. Ports $((BASE_PORT+1))+ bind to 127.0.0.1 only."
